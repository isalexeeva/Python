import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt

# Пример данных (замените на ваши реальные данные)
data = {
    'age': [25, 30, 35, 40, 45, 50, 55, 60, 65, 70],
    'spending_score': [50, 60, 70, 80, 75, 65, 55, 45, 35, 25]
}

# Создаем DataFrame
df = pd.DataFrame(data)

# Проверка данных
print(df.info())  # Проверяем наличие пропусков и типы данных
print(df.head())  # Просматриваем первые строки данных

# Преобразуем данные в числовой формат, если это необходимо
df['age'] = pd.to_numeric(df['age'])
df['spending_score'] = pd.to_numeric(df['spending_score'])

# Построение линейного графика
plt.figure(figsize=(10, 6))  # Устанавливаем размер графика
sns.lineplot(x='age', y='spending_score', data=df, marker='o')  # Строим график

# Настройка оформления
plt.title('Зависимость балла по расходам от возраста', fontsize=16)  # Заголовок
plt.xlabel('Возраст (age)', fontsize=14)  # Метка оси X
plt.ylabel('Балл по расходам (spending_score)', fontsize=14)  # Метка оси Y
plt.grid(True)  # Добавляем сетку для удобства чтения

# Отображение графика
plt.show()