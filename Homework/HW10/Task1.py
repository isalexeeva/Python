import pandas as pd
import random

# Создаем исходный DataFrame
lst = ['robot'] * 10
lst += ['human'] * 10
random.shuffle(lst)
data = pd.DataFrame({'whoAmI': lst})

# Извлекаем уникальные значения из столбца 'whoAmI'
unique_values = data['whoAmI'].unique()

# Создаем новый DataFrame для хранения one-hot кодирования
one_hot_data = pd.DataFrame()

# Для каждого уникального значения создаем бинарный столбец
for value in unique_values:
    one_hot_data[value] = (data['whoAmI'] == value).astype(int)

# Объединяем исходный DataFrame с новым DataFrame, содержащим one-hot кодирование
result = pd.concat([data, one_hot_data], axis=1)

# Выводим результат
print(result.head())